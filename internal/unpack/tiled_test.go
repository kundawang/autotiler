// quadColor returns the fixed unique color of the source sub tile at (x, y)
// in the synthetic packed sources generated by makePackedSource.
func quadColor(x, y int) color.NRGBA {
	return color.NRGBA{
		R: uint8(10 + x*40),
		G: uint8(10 + y*35),
		B: uint8(250 - x*7 - y*5),
		A: 255,
	}
}

// makePackedSource builds a synthetic 2x3 packed tileset where every sub tile
// quadrant is filled with a fixed unique color, so any output pixel can be
// traced back to its source quadrant.
func makePackedSource(tileWidth, tileHeight int) *image.NRGBA {
	img := image.NewNRGBA(image.Rect(0, 0, tileWidth*2, tileHeight*3))
	halfW := tileWidth / 2
	halfH := tileHeight / 2
	for qy := 0; qy < 6; qy++ {
		for qx := 0; qx < 4; qx++ {
			c := quadColor(qx, qy)
			for y := qy * halfH; y < (qy+1)*halfH; y++ {
				for x := qx * halfW; x < (qx+1)*halfW; x++ {
					img.SetNRGBA(x, y, c)
				}
			}
		}
	}
	return img
}

// topLeftQuadAfterRotation maps a counter-clockwise rotation in degrees to the
// index (in TileMeta.Quads order: TL, TR, BL, BR) of the source quadrant that
// ends up in the top-left corner of the placed tile.
var topLeftQuadAfterRotation = map[int]int{0: 0, 90: 1, 180: 3, 270: 2}

func sheetExports() []struct {
	name string
	fn   func(*Unpacker) (*Sheet, error)
	cols int
	rows int
} {
	return []struct {
		name string
		fn   func(*Unpacker) (*Sheet, error)
		cols int
		rows int
	}{
		{"16x1_terrain1", (*Unpacker).From6to16Terrain1, 16, 1},
		{"16x1_terrain2", (*Unpacker).From6to16Terrain2, 16, 1},
		{"14x2", (*Unpacker).From6to28, 14, 2},
		{"12x4_terrain1", (*Unpacker).From6to48Terrain1, 12, 4},
		{"12x4_terrain2", (*Unpacker).From6to48Terrain2, 12, 4},
	}
}

// TestTiledTilesetMatchesPixels runs three fixed packed tilemaps through every
// export layout and verifies, for every tile ID in the generated Tiled JSON,
// that the tile's recorded source quadrants match the actual pixels on the
// exported sheet.
func TestTiledTilesetMatchesPixels(t *testing.T) {
	fixtures := []struct {
		name              string
		tileW, tileH, pad int
	}{
		{"tile8_nopad", 8, 8, 0},
		{"tile8_pad1", 8, 8, 1},
		{"tile16_pad2", 16, 16, 2},
	}
	for _, fx := range fixtures {
		fx := fx
		t.Run(fx.name, func(t *testing.T) {
			src := makePackedSource(fx.tileW, fx.tileH)
			u := NewUnpacker(src, 2, 3, fx.pad)
			if err := u.Init(2); err != nil {
				t.Fatalf("Init: %v", err)
			}
			for _, exp := range sheetExports() {
				exp := exp
				t.Run(exp.name, func(t *testing.T) {
					sheet, err := exp.fn(u)
					if err != nil {
						t.Fatalf("export: %v", err)
					}
					checkSheetLayout(t, sheet, exp.cols, exp.rows, fx.tileW, fx.tileH, fx.pad)
					ts := NewTiledTileset(exp.name, exp.name+".png", sheet, fx.tileW, fx.tileH, fx.pad)
					checkTiledHeader(t, ts, sheet, exp.name, fx.tileW, fx.tileH, fx.pad)
					checkTilesAgainstPixels(t, ts, sheet, fx.tileW, fx.tileH, fx.pad)
				})
			}
		})
	}
}

func checkSheetLayout(t *testing.T, sheet *Sheet, cols, rows, tileW, tileH, pad int) {
	t.Helper()
	if sheet.Columns != cols || sheet.Rows != rows {
		t.Fatalf("sheet layout = %dx%d, want %dx%d", sheet.Columns, sheet.Rows, cols, rows)
	}
	wantW := cols * (tileW + 2*pad)
	wantH := rows * (tileH + 2*pad)
	if got := sheet.Canvas.Bounds().Dx(); got != wantW {
		t.Fatalf("canvas width = %d, want %d", got, wantW)
	}
	if got := sheet.Canvas.Bounds().Dy(); got != wantH {
		t.Fatalf("canvas height = %d, want %d", got, wantH)
	}
	if len(sheet.Tiles) != cols*rows {
		t.Fatalf("len(sheet.Tiles) = %d, want %d", len(sheet.Tiles), cols*rows)
	}
}

func checkTiledHeader(t *testing.T, ts *TiledTileset, sheet *Sheet, name string, tileW, tileH, pad int) {
	t.Helper()
	if ts.Columns != sheet.Columns {
		t.Errorf("columns = %d, want %d", ts.Columns, sheet.Columns)
	}
	if ts.TileCount != sheet.Columns*sheet.Rows {
		t.Errorf("tilecount = %d, want %d", ts.TileCount, sheet.Columns*sheet.Rows)
	}
	if ts.TileWidth != tileW || ts.TileHeight != tileH {
		t.Errorf("tile size = %dx%d, want %dx%d", ts.TileWidth, ts.TileHeight, tileW, tileH)
	}
	if ts.ImageWidth != sheet.Canvas.Bounds().Dx() || ts.ImageHeight != sheet.Canvas.Bounds().Dy() {
		t.Errorf("image size = %dx%d, want %dx%d",
			ts.ImageWidth, ts.ImageHeight, sheet.Canvas.Bounds().Dx(), sheet.Canvas.Bounds().Dy())
	}
	if ts.Margin != pad || ts.Spacing != 2*pad {
		t.Errorf("margin/spacing = %d/%d, want %d/%d", ts.Margin, ts.Spacing, pad, 2*pad)
	}
	if ts.Image != name+".png" {
		t.Errorf("image = %q, want %q", ts.Image, name+".png")
	}
	if len(ts.Tiles) != ts.TileCount {
		t.Fatalf("len(tiles) = %d, want tilecount %d", len(ts.Tiles), ts.TileCount)
	}
	for id, tile := range ts.Tiles {
		if tile.ID != id {
			t.Fatalf("tile at position %d has id %d", id, tile.ID)
		}
	}
}

// checkTilesAgainstPixels verifies that for every tile ID the source quadrant
// recorded in the JSON properties matches the pixel actually present at the
// tile's top-left corner on the sheet, taking the recorded rotation and the
// padding into account.
func checkTilesAgainstPixels(t *testing.T, ts *TiledTileset, sheet *Sheet, tileW, tileH, pad int) {
	t.Helper()
	paddedW := tileW + 2*pad
	paddedH := tileH + 2*pad
	for id, meta := range sheet.Tiles {
		quads, rotation := parseTileProperties(t, ts.Tiles[id])
		if rotation != meta.Rotation {
			t.Errorf("tile %d: json rotation %d, sheet meta %d", id, rotation, meta.Rotation)
		}
		if quads != meta.Quads {
			t.Errorf("tile %d: json quads %v, sheet meta %v", id, quads, meta.Quads)
		}
		srcQuad, ok := topLeftQuadAfterRotation[rotation]
		if !ok {
			t.Fatalf("tile %d: unexpected rotation %d", id, rotation)
		}
		q := quads[srcQuad]
		want := quadColor(q[0], q[1])
		col := id % sheet.Columns
		row := id / sheet.Columns
		got := sheet.Canvas.NRGBAAt(col*paddedW+pad, row*paddedH+pad)
		if got != want {
			t.Errorf("tile %d (col %d, row %d): top-left pixel = %v, want %v (source quad %v, rotation %d)",
				id, col, row, got, want, q, rotation)
		}
	}
}

// parseTileProperties extracts the quads and rotation custom properties from a
// Tiled tile entry and decodes them back into a TileMeta-shaped value.
func parseTileProperties(t *testing.T, tile TiledTile) ([4][2]int, int) {
	t.Helper()
	var quads [4][2]int
	var rotation int
	seenQuads, seenRotation := false, false
	for _, prop := range tile.Properties {
		switch prop.Name {
		case "quads":
			seenQuads = true
			value, ok := prop.Value.(string)
			if !ok {
				t.Fatalf("tile %d: quads property is not a string: %T", tile.ID, prop.Value)
			}
			parts := strings.Split(value, ";")
			if len(parts) != 4 {
				t.Fatalf("tile %d: quads property %q does not have 4 entries", tile.ID, value)
			}
			for i, part := range parts {
				if _, err := fmt.Sscanf(part, "%d,%d", &quads[i][0], &quads[i][1]); err != nil {
					t.Fatalf("tile %d: cannot parse quad %q: %v", tile.ID, part, err)
				}
			}
		case "rotation":
			seenRotation = true
			switch v := prop.Value.(type) {
			case int:
				rotation = v
			case string:
				parsed, err := strconv.Atoi(v)
				if err != nil {
					t.Fatalf("tile %d: cannot parse rotation %q: %v", tile.ID, v, err)
				}
				rotation = parsed
			default:
				t.Fatalf("tile %d: rotation property has unexpected type %T", tile.ID, prop.Value)
			}
		}
	}
	if !seenQuads || !seenRotation {
		t.Fatalf("tile %d: missing quads or rotation property", tile.ID)
	}
	return quads, rotation
}

// TestTiledJSONRoundTrip verifies the generated tileset survives a JSON
// marshal/unmarshal round trip with indices and header fields intact.
func TestTiledJSONRoundTrip(t *testing.T) {
	src := makePackedSource(8, 8)
	u := NewUnpacker(src, 2, 3, 0)
	if err := u.Init(2); err != nil {
		t.Fatalf("Init: %v", err)
	}
	sheet, err := u.From6to28()
	if err != nil {
		t.Fatalf("export: %v", err)
	}
	ts := NewTiledTileset("roundtrip", "roundtrip.png", sheet, 8, 8, 0)
	data, err := json.Marshal(ts)
	if err != nil {
		t.Fatalf("marshal: %v", err)
	}
	var decoded TiledTileset
	if err := json.Unmarshal(data, &decoded); err != nil {
		t.Fatalf("unmarshal: %v", err)
	}
	if decoded.Columns != 14 || decoded.TileCount != 28 || decoded.TileWidth != 8 || decoded.TileHeight != 8 {
		t.Errorf("decoded header mismatch: %+v", decoded)
	}
	if len(decoded.Tiles) != 28 {
		t.Fatalf("decoded tiles = %d, want 28", len(decoded.Tiles))
	}
	for id, tile := range decoded.Tiles {
		if tile.ID != id {
			t.Fatalf("decoded tile at position %d has id %d", id, tile.ID)
		}
	}
}

func TestWriteTiledJSONOverwrite(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "sheet.json")
	ts := &TiledTileset{Name: "sheet", Type: "tileset"}

	if err := WriteTiledJSON(path, ts, false); err != nil {
		t.Fatalf("first write: %v", err)
	}
	if _, err := os.Stat(path); err != nil {
		t.Fatalf("expected file to exist: %v", err)
	}

	err := WriteTiledJSON(path, ts, false)
	if !errors.Is(err, ErrOutputExists) {
		t.Fatalf("second write without force: got %v, want ErrOutputExists", err)
	}

	if err := WriteTiledJSON(path, ts, true); err != nil {
		t.Fatalf("forced write: %v", err)
	}
}

func TestInitValidation(t *testing.T) {
	tests := []struct {
		name    string
		w, h    int
		xTiles  int
		yTiles  int
		wantErr error
	}{
		{"valid", 16, 24, 2, 3, nil},
		{"non_divisible_height", 16, 20, 2, 3, ErrNonDivisibleImage},
		{"non_divisible_width", 15, 24, 2, 3, ErrNonDivisibleImage},
		{"odd_tile_width", 6, 12, 2, 3, ErrInvalidTileSize},
		{"tile_too_small", 2, 6, 2, 3, ErrInvalidTileSize},
		{"non_square_tile", 8, 18, 2, 3, ErrInvalidTileSize},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			img := image.NewNRGBA(image.Rect(0, 0, tt.w, tt.h))
			u := NewUnpacker(img, tt.xTiles, tt.yTiles, 0)
			err := u.Init(2)
			if tt.wantErr == nil {
				if err != nil {
					t.Fatalf("Init: unexpected error %v", err)
				}
				return
			}
			if !errors.Is(err, tt.wantErr) {
				t.Fatalf("Init: got %v, want %v", err, tt.wantErr)
			}
		})
	}
}
